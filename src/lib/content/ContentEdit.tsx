'use client';

/**
 * ContentEdit — in-place editing of the public site's copy, for the team.
 *
 * Same shape as the Zuka CMS: a signed-in user hits "Edit page" and types
 * straight into the live page. No separate editor screen, no page templates
 * to keep in sync with the design.
 *
 * Firestore layout (in the `oynamak` database, rules in firestore.rules):
 *   content/{pageId}          → flat map of string key → string value.
 *                               Keys are dot-paths ("hero.title") stored as
 *                               LITERAL field names (setDoc does not expand
 *                               dots the way updateDoc does).
 *   images/{pageId}__{key}    → { dataUrl, updatedAt } for replaced images.
 *                               The content doc's value for an image key is
 *                               the image doc id.
 *
 * Usage (per page):
 *
 *   'use client';
 *   import { PageContent } from '@/lib/content/ContentEdit';
 *   import { EText, EImage } from '@/components/site/Editable';
 *
 *   export default function Page() {
 *     return (
 *       <PageContent id="about">
 *         <EText k="hero.title" fallback="Oynamak Sports Group Ltd" as="h1" className="..." />
 *         <EText k="hero.tagline" fallback="Long copy..." as="p" />
 *         <EImage k="hero.photo" fallbackSrc="/oaktree1.jpeg" alt="Team" fill />
 *       </PageContent>
 *     );
 *   }
 *
 * Fallbacks are the shipped copy: until an admin edits a key, the page
 * renders exactly what is in the code, so nothing regresses if Firestore is
 * empty or unreachable.
 *
 * Edit mode itself comes from <EditModeProvider> + <EditToolbar/>, mounted
 * once in src/app/layout.tsx — pages only add <PageContent> and the editable
 * components.
 */

import {
    createContext,
    useCallback,
    useContext,
    useEffect,
    useMemo,
    useState,
    type ReactNode,
} from 'react';
import { doc, onSnapshot, serverTimestamp, setDoc } from 'firebase/firestore';
import { db } from '@/lib/firebase';
import { useAuthContext } from '@/contexts/AuthContext';
import { isActive } from '@/lib/roles';
import snapshotJson from './content-snapshot.json';

/**
 * Build-time snapshot of the edited content (scripts/snapshot-content.mjs,
 * regenerated by the npm "prebuild" step). It is the INITIAL state for every
 * page, so the first paint shows the last-published edited copy rather than
 * the hardcoded fallbacks; the live subscription then applies anything edited
 * since the deploy.
 */
const SNAPSHOT = snapshotJson as { pages: Record<string, ContentMap>; images: Record<string, string> };

/** Static file extracted at build time for an images/{docId} doc, if any. */
export function snapshotImageSrc(docId: string): string | null {
    return (docId && SNAPSHOT.images[docId]) || null;
}

/* ────────────────────────────────────────────────────────────────────────
 * Edit mode
 * ──────────────────────────────────────────────────────────────────────── */

export interface EditModeValue {
    /** True only when the signed-in user has access AND toggled edit mode on. */
    editing: boolean;
    setEditing: (on: boolean) => void;
    /** Whether the toolbar should offer the toggle at all. */
    canEdit: boolean;
}

const EditModeContext = createContext<EditModeValue | null>(null);

/**
 * Provides edit-mode state for a subtree (mounted once in the root layout).
 * `editing` can only ever be true for someone with an active console account —
 * for everyone else the value is permanently false no matter what setEditing is
 * called with. Firestore rules enforce the same thing server-side; this is only
 * about the UI.
 */
export function EditModeProvider({ children }: { children: ReactNode }) {
    const { profile, loading } = useAuthContext();
    const canEdit = !loading && isActive(profile);
    const [on, setOn] = useState(false);

    const value = useMemo<EditModeValue>(
        () => ({ editing: canEdit && on, setEditing: setOn, canEdit }),
        [canEdit, on],
    );

    return <EditModeContext.Provider value={value}>{children}</EditModeContext.Provider>;
}

const EDIT_MODE_OFF: EditModeValue = { editing: false, setEditing: () => { }, canEdit: false };

/**
 * Read edit-mode state. Safe to call outside <EditModeProvider> (e.g. from a
 * component reused inside /ops): returns a permanently-off value.
 */
export function useEditMode(): EditModeValue {
    return useContext(EditModeContext) ?? EDIT_MODE_OFF;
}

/* ────────────────────────────────────────────────────────────────────────
 * Page content
 * ──────────────────────────────────────────────────────────────────────── */

export interface PageContentValue {
    /** The page's content doc id (content/{pageId}); also namespaces image docs. */
    pageId: string;
    /** Current value for a key, or `fallback` while loading / when unedited. */
    get: (key: string, fallback: string) => string;
    /** Persist a value (console accounts only, per Firestore rules). setDoc + merge. */
    set: (key: string, value: string) => Promise<void>;
}

type ContentMap = Record<string, unknown>;

const PageContentContext = createContext<PageContentValue | null>(null);

const EMPTY_CONTENT: ContentMap = {};

/** Walk a dot-path into nested maps (safety net for hand-seeded docs). */
function readPath(data: ContentMap, key: string): unknown {
    let cur: unknown = data;
    for (const part of key.split('.')) {
        if (typeof cur !== 'object' || cur === null) return undefined;
        cur = (cur as ContentMap)[part];
    }
    return cur;
}

/** Internal: one live subscription to content/{pageId}. Pass null to disable. */
function useContentDoc(pageId: string | null): PageContentValue {
    // State is keyed by the doc id it came from, so switching pages never
    // needs a synchronous reset inside the effect — stale data is simply
    // ignored by the derivation below until the new snapshot arrives.
    const [snap, setSnap] = useState<{ id: string; data: ContentMap } | null>(null);

    useEffect(() => {
        if (!pageId) return;
        return onSnapshot(
            doc(db, 'content', pageId),
            (s) => setSnap({ id: pageId, data: s.exists() ? (s.data() as ContentMap) : {} }),
            () => setSnap({ id: pageId, data: {} }),
        );
    }, [pageId]);

    // Until the live doc arrives, serve the build-time snapshot of the edited
    // copy (falling back to the shipped strings only for never-edited keys).
    const data: ContentMap =
        snap && snap.id === pageId
            ? snap.data
            : (pageId && SNAPSHOT.pages[pageId]) || EMPTY_CONTENT;

    const get = useCallback(
        (key: string, fallback: string): string => {
            const flat = data[key]; // keys are stored literally, dots included
            if (typeof flat === 'string') return flat;
            const nested = readPath(data, key);
            return typeof nested === 'string' ? nested : fallback;
        },
        [data],
    );

    const set = useCallback(
        async (key: string, value: string) => {
            if (!pageId) throw new Error('ContentEdit: set() called without a pageId');
            await setDoc(doc(db, 'content', pageId), { [key]: value }, { merge: true });
        },
        [pageId],
    );

    return useMemo(() => ({ pageId: pageId ?? '', get, set }), [pageId, get, set]);
}

/**
 * Wrap a page once so every nested <EText>/<EImage> shares ONE Firestore
 * subscription to content/{id}.
 */
export function PageContent({ id, children }: { id: string; children: ReactNode }) {
    const value = useContentDoc(id);
    return <PageContentContext.Provider value={value}>{children}</PageContentContext.Provider>;
}

/**
 * Access page content. Inside a matching <PageContent> wrapper this reuses
 * the shared subscription; called with an explicit `pageId` outside one (or
 * for a different page) it opens its own.
 */
export function usePageContent(pageId?: string): PageContentValue {
    const ctx = useContext(PageContentContext);
    const needOwn = !ctx || (pageId !== undefined && ctx.pageId !== pageId);
    const own = useContentDoc(needOwn ? (pageId ?? null) : null);
    if (!needOwn) return ctx as PageContentValue;
    if (!pageId) {
        throw new Error('usePageContent: no <PageContent> ancestor — pass a pageId or add the wrapper');
    }
    return own;
}

/* ────────────────────────────────────────────────────────────────────────
 * Image docs (used by <EImage>)
 * ──────────────────────────────────────────────────────────────────────── */

export interface ImageDoc {
    dataUrl?: string;
    updatedAt?: unknown;
}

/** Subscribe to images/{docId}; returns its dataUrl or null. Pass "" to skip. */
export function useImageDoc(docId: string): string | null {
    const [snap, setSnap] = useState<{ id: string; dataUrl: string | null } | null>(null);

    useEffect(() => {
        if (!docId) return;
        return onSnapshot(
            doc(db, 'images', docId),
            (s) => {
                const d = s.exists() ? (s.data() as ImageDoc) : null;
                setSnap({ id: docId, dataUrl: typeof d?.dataUrl === 'string' ? d.dataUrl : null });
            },
            () => setSnap({ id: docId, dataUrl: null }),
        );
    }, [docId]);

    return docId && snap && snap.id === docId ? snap.dataUrl : null;
}

/** Write images/{docId} = { dataUrl, updatedAt } (console accounts only, per rules). */
export async function saveImageDoc(docId: string, dataUrl: string): Promise<void> {
    await setDoc(doc(db, 'images', docId), { dataUrl, updatedAt: serverTimestamp() }, { merge: true });
}
